def destindex_copy_kv(
    K,
    Out,
    Dest_loc,
    B,
    H,
    D,
    seq_len,
    head_num,
    offs_h,
    stride_h,
    stride_d,
    stride_b,
    stride_k,
    grid_stride_h,
    grid_stride_d,
    grid_stride_b,
    grid_stride_k,
    out_stride_h,
    out_stride_d,
    out_stride_b,
    out_stride_k,
    mask_k,
    mask_h,
    mask_d,
    mask_b,
    block_k,
    block_h,
    block_d,
    block_b,
):
    assert K.shape == Out.shape
    assert len(Dest_loc.shape) == 2 and Dest_loc.shape[1] == 3
    BLOCK_HEAD = triton.next_power_of_2(head_num)
    grid = lambda meta: (meta[0],)
    _fwd_kernel_destindex_copy_kv[grid](
        K.data_ptr(),
        Out.data_ptr(),
        Dest_loc.data_ptr(),
        B,
        H,
        D,
        seq_len,
        head_num,
        offs_h,
        stride_h,
        stride_d,
        stride_b,
        stride_k,
        grid_stride_h,
        grid_stride_d,
        grid_stride_b,
        grid_stride_k,
        out_stride_h,
        out_stride_d,
        out_stride_b,
        out_stride_k,
        mask_k,
        mask_h,
        mask_d,
        mask_b,
        block_k,
        block_h,
        block_d,
        block_b,
    )
